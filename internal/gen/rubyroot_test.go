func TestRubyRoot_RootPrefixPrefixesEveryAlias(t *testing.T) {
	files := map[string]string{
		"shop/deployment.proto": shopDeployment + "option (mesh.root_prefix) = \"Shop\";\n",
		"shop/order.proto":      rootService,
	}
	_, src := rubyRoot(t, files, "Definitions")
	want := `  # shop/order.proto
  ShopStatus = ::Shop::Status
  ShopOrder = ::Shop::Order
  ShopOrderService = ::Shop::OrderService
  ShopOrderClient = ::Shop::OrderClient
  ShopOrderTargets = ::Shop::OrderTargets

  ServiceMaps = ::ServiceMaps
end
`
	if !strings.HasSuffix(src, "module Definitions\n"+want) {
		t.Fatalf("got:\n%s", src)
	}
}
