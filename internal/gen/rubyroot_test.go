func TestRubyRoot_AliasesEveryTopLevelConstant(t *testing.T) {
	_, src := rubyRoot(t, rootFixture, "Definitions")
	want := `# frozen_string_literal: true

# Generated by grpc-service-mesh-gen. DO NOT EDIT.
# Every generated constant of the definitions tree, under one module.

require "shop/deployment_pb"
require "shop/order_pb"
require "shop/shop_grpcmesh"
require "service_maps"

module Definitions
  # shop/order.proto
  Status = ::Shop::Status
  Order = ::Shop::Order
  OrderService = ::Shop::OrderService
  OrderClient = ::Shop::OrderClient
  OrderTargets = ::Shop::OrderTargets

  ServiceMaps = ::ServiceMaps
end
`
	if src != want {
		t.Fatalf("got:\n%s", src)
	}
}

func TestRubyRoot_MessagesOnlyDirectoryIsRequiredAndAliased(t *testing.T) {
	files := map[string]string{
		"shop/deployment.proto": shopDeployment,
		"shop/order.proto":      shopService,
		"common/id.proto":       "syntax = \"proto3\";\npackage common;\nmessage Id {}\n",
	}
	_, src := rubyRoot(t, files, "Definitions")
	mustContain(t, src, "require \"common/id_pb\"\nrequire \"shop/deployment_pb\"\n")
	mustContain(t, src, "\n  # common/id.proto\n  Id = ::Common::Id\n")
}

func TestRubyRoot_FileWithNothingToAliasIsRequiredOnly(t *testing.T) {
	files := map[string]string{
		"shop/deployment.proto": shopDeployment,
		"shop/order.proto":      shopService,
		"common/options.proto": `syntax = "proto3";
package common;
import "google/protobuf/descriptor.proto";
extend google.protobuf.MessageOptions { string owner = 50100; }
`,
	}
	_, src := rubyRoot(t, files, "Definitions")
	mustContain(t, src, "require \"common/options_pb\"\n")
	mustNotContain(t, src, "# common/options.proto")
}

func TestRubyRoot_RubyPackageNamesTheSourceModule(t *testing.T) {
	files := map[string]string{
		"shop/deployment.proto": shopDeployment,
		"shop/order.proto":      shopService + "option ruby_package = \"Example::Shop\";\n",
	}
	_, src := rubyRoot(t, files, "Definitions")
	mustContain(t, src, "  Order = ::Example::Shop::Order\n")
	mustContain(t, src, "  OrderClient = ::Example::Shop::OrderClient\n")
}

func TestRubyRoot_DuplicateConstantAcrossDirectories(t *testing.T) {
	files := map[string]string{
		"shop/deployment.proto": shopDeployment,
		"shop/order.proto":      shopService,
		"common/key.proto":      "syntax = \"proto3\";\npackage common;\nmessage Order {}\n",
	}
	got := rubyRootErr(t, files, "Definitions")
	if got != "root module Definitions: Order is generated by both common/key.proto and shop/order.proto; set option (mesh.root_prefix) in one of their directories" {
		t.Fatalf("got:\n%s", got)
	}
}

