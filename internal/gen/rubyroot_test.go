func rubyRoot(t *testing.T, files map[string]string, module string) (string, string) {
	t.Helper()
	p, b, err := RubyRoot(analyze(t, files), module)
	if err != nil {
		t.Fatal(err)
	}
	return p, string(b)
}

func rubyRootErr(t *testing.T, files map[string]string, module string) string {
	t.Helper()
	_, _, err := RubyRoot(analyze(t, files), module)
	if err == nil {
		t.Fatal("RubyRoot returned no error")
	}
	return err.Error()
}

func TestParseRubyRootModule_OneConstant(t *testing.T) {
	got, err := ParseRubyRootModule("Definitions")
	if err != nil || got != "Definitions" {
		t.Fatalf("got %q, %v", got, err)
	}
}

func TestParseRubyRootModule_NestedNameIsRejected(t *testing.T) {
	_, err := ParseRubyRootModule("My::Definitions")
	if err == nil || err.Error() != `--ruby-root-module: "My::Definitions" is not a Ruby module name; one constant such as Definitions is expected` {
		t.Fatalf("err %v", err)
	}
}

