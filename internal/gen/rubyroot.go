package gen

import (
	"bytes"
	"fmt"
	"path"
	"regexp"
	"strings"

	"github.com/Paymentbox-com/grpc-service-mesh-api"
)

var rubyConstant = regexp.MustCompile(`^[A-Z][A-Za-z0-9_]*$`)

// ParseRubyRootModule reads a --ruby-root-module value, one Ruby constant
// name such as PmtboxMesh.
func ParseRubyRootModule(s string) (string, error) {
	if !rubyConstant.MatchString(s) {
		return "", fmt.Errorf("--ruby-root-module: %q is not a Ruby module name; one constant such as PmtboxMesh is expected", s)
	}
	return s, nil
}

// RubyRoot renders <snake_case(module)>_grpcmesh.rb at the Ruby output root:
// an alias of every generated Ruby constant of every source file, under one
// module. Nested messages and enums are reached through their parent.
func RubyRoot(m *Model, module string) (string, []byte, error) {
	var errs []string
	seen := map[string]string{} // constant -> file that generates it
	var body bytes.Buffer
	for _, src := range m.Sources {
		mod := rubyModule(src.Package, src.RubyPackage)
		if strings.SplitN(mod, "::", 2)[0] == module {
			errs = append(errs, fmt.Sprintf("root module %s: %s generates a module with the same name", module, src.Path))
		}
		prefix := "::" + mod + "::"
		var lines []string
		add := func(name string) {
			if prev, dup := seen[name]; dup {
				errs = append(errs, fmt.Sprintf("root module %s: %s is generated by both %s and %s", module, name, prev, src.Path))
				return
			}
			seen[name] = src.Path
			lines = append(lines, fmt.Sprintf("  %s = %s%s", name, prefix, name))
		}
		enums := src.Desc.Enums()
		for i := 0; i < enums.Len(); i++ {
			add(upperFirst(string(enums.Get(i).Name())))
		}
		msgs := src.Desc.Messages()
		for i := 0; i < msgs.Len(); i++ {
			add(upperFirst(string(msgs.Get(i).Name())))
		}
		for _, s := range src.Services {
			base := upperFirst(BaseName(s.Name))
			add(upperFirst(s.Name))
			add(base + "Client")
			add(base + "Targets")
		}
		if len(lines) == 0 {
			continue
		}
		fmt.Fprintf(&body, "\n  # %s\n%s\n", src.Path, strings.Join(lines, "\n"))
	}
	if module == "ServiceMaps" {
		errs = append(errs, fmt.Sprintf("root module %s: service_maps.rb defines a module with the same name", module))
	}
	body.WriteString("\n  ServiceMaps = ::ServiceMaps\n")
	if len(errs) > 0 {
		return "", nil, fmt.Errorf("%s", strings.Join(errs, "\n"))
	}

	var b bytes.Buffer
	b.WriteString("# frozen_string_literal: true\n\n")
	b.WriteString("# Generated by grpc-service-mesh-gen. DO NOT EDIT.\n")
	b.WriteString("# Every generated constant of the definitions tree, under one module.\n\n")
	fmt.Fprintf(&b, "require %s\n", rubyString(rubyRequirePath(spec.OptionsProto)))
	for _, src := range m.Sources {
		fmt.Fprintf(&b, "require %s\n", rubyString(rubyRequirePath(src.Path)))
	}
	for _, d := range m.Directories {
		fmt.Fprintf(&b, "require %s\n", rubyString(path.Join(d.Path, path.Base(d.Path)+"_grpcmesh")))
	}
	b.WriteString("require \"service_maps\"\n")
	fmt.Fprintf(&b, "\nmodule %s\n", module)
	b.WriteString(strings.TrimPrefix(body.String(), "\n"))
	b.WriteString("end\n")
	return SnakeCase(module) + "_grpcmesh.rb", b.Bytes(), nil
}
