// rootService declares, in pbx/api_key.proto, a top-level enum, a message
// with a nested enum and a nested message, and a service with a ROUTE and a
// TOPIC method.
const rootService = header + `package pbx;
import "google/protobuf/empty.proto";
option go_package = "github.com/Paymentbox-com/pbx";
enum Status { ACTIVE = 0; REVOKED = 1; }
message ApiKey {
  enum Scope { READ = 0; WRITE = 1; }
  message Owner { string name = 1; }
  Status status = 1;
  Scope scope = 2;
  Owner owner = 3;
  map<string, string> labels = 4;
}
service ApiKeyService {
  rpc Search(ApiKey) returns (ApiKey);
  rpc Created(ApiKey) returns (google.protobuf.Empty) {
    option (mesh.kind) = TOPIC;
  }
}
`

// rootFixture is the definitions tree the root file tests share.
var rootFixture = map[string]string{"pbx/deployment.proto": pbxDeployment, "pbx/api_key.proto": rootService}

func goRoot(t *testing.T, files map[string]string, rootPackage string) (string, string) {
	t.Helper()
	p, b, err := GoRoot(analyze(t, files), rootPackage)
	if err != nil {
		t.Fatal(err)
	}
	return p, string(b)
}

func goRootErr(t *testing.T, files map[string]string, rootPackage string) string {
	t.Helper()
	_, _, err := GoRoot(analyze(t, files), rootPackage)
	if err == nil {
		t.Fatal("GoRoot returned no error")
	}
	return err.Error()
}

func TestParseGoRootPackage_NameIsTheLastPathElement(t *testing.T) {
	importPath, name, err := ParseGoRootPackage("github.com/Paymentbox-com/pmtbox_mesh")
	if err != nil || importPath != "github.com/Paymentbox-com/pmtbox_mesh" || name != "pmtbox_mesh" {
		t.Fatalf("got %q, %q, %v", importPath, name, err)
	}
}

func TestParseGoRootPackage_ExplicitName(t *testing.T) {
	importPath, name, err := ParseGoRootPackage("github.com/Paymentbox-com/pmtbox_mesh;pmtboxmesh")
	if err != nil || importPath != "github.com/Paymentbox-com/pmtbox_mesh" || name != "pmtboxmesh" {
		t.Fatalf("got %q, %q, %v", importPath, name, err)
	}
}

func TestParseGoRootPackage_EmptyPath(t *testing.T) {
	_, _, err := ParseGoRootPackage(";pmtboxmesh")
	if err == nil || err.Error() != "--go-root-package needs an import path" {
		t.Fatalf("err %v", err)
	}
}

func TestParseGoRootPackage_NameThatIsNotAnIdentifier(t *testing.T) {
	_, _, err := ParseGoRootPackage("github.com/Paymentbox-com/pmtbox_mesh;pmtbox-mesh")
	if err == nil || err.Error() != `--go-root-package: "pmtbox-mesh" is not a Go package name` {
		t.Fatalf("err %v", err)
	}
}

