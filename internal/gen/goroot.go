// ParseGoRootPackage reads a --go-root-package value, an import path with an
// optional ";name" as in go_package, and returns the import path and the
// package name.
func ParseGoRootPackage(s string) (importPath, name string, err error) {
	importPath, name = splitGoPackage(s)
	switch {
	case importPath == "":
		return "", "", fmt.Errorf("--go-root-package needs an import path")
	case name == "" || goIdent(name) != name || name == "_":
		return "", "", fmt.Errorf("--go-root-package: %q is not a Go package name", name)
	}
	return importPath, name, nil
}

// goPlugin runs protoc-gen-go's front end over the model's sources, the way
// the message run does, so the Go identifiers it would generate are known.
func goPlugin(m *Model) (*protogen.Plugin, error) {
	params := []string{"paths=source_relative", "M" + spec.OptionsProto + "=" + spec.OptionsGoImport}
	overrides := GoImportOverrides(m)
	files := make([]string, 0, len(overrides))
	for f := range overrides {
		files = append(files, f)
	}
	sort.Strings(files)
	for _, f := range files {
		params = append(params, "M"+f+"="+overrides[f])
	}
	req := &pluginpb.CodeGeneratorRequest{Parameter: proto.String(strings.Join(params, ","))}
	for _, src := range m.Sources {
		req.FileToGenerate = append(req.FileToGenerate, src.Path)
	}
	req.ProtoFile = m.set.GetFile()
	return protogen.Options{}.New(req)
}

// GoRoot renders <name>.grpcmesh.go at the Go output root: an alias of every
// generated Go identifier of every source file, under one package.
func GoRoot(m *Model, rootPackage string) (string, []byte, error) {
	rootPath, rootName := splitGoPackage(rootPackage)
	plugin, err := goPlugin(m)
	if err != nil {
		return "", nil, fmt.Errorf("root package %s: %w", rootName, err)
	}

	var errs []string
	seen := map[string]string{} // identifier -> file that generates it
	im := newGoImports(rootPath, rootName)
	var order []string // import paths in first-seen order
	imported := map[string]bool{}
	aliased := map[string]bool{}
	var body bytes.Buffer
	for _, src := range m.Sources {
		f := plugin.FilesByPath[src.Path]
		pkgPath, pkgName := string(f.GoImportPath), string(f.GoPackageName)
		if pkgName == rootName {
			errs = append(errs, fmt.Sprintf("root package %s: %s generates a package with the same name", rootName, src.Path))
		}
		if !imported[pkgPath] {
			imported[pkgPath] = true
			order = append(order, pkgPath)
		}
		// One line per identifier, grouped by keyword so gofmt separates the
		// groups and nothing else.
		lines := map[string][]string{}
		add := func(keyword, name string) {
			if prev, dup := seen[name]; dup {
				errs = append(errs, fmt.Sprintf("root package %s: %s is generated by both %s and %s", rootName, name, prev, src.Path))
				return
			}
			seen[name] = src.Path
			lines[keyword] = append(lines[keyword], fmt.Sprintf("%s %s = %s.%s", keyword, name, im.use(pkgPath, pkgName), name))
		}
		for _, e := range f.Enums {
			goEnumAliases(e, add)
		}
		goMessageAliases(f.Messages, add)
		for _, s := range src.Services {
			base := BaseName(s.Name)
			add("type", s.Name)
			add("var", base+"Client")
			add("var", base+"Targets")
		}
		if len(lines) == 0 {
			continue
		}
		aliased[pkgPath] = true
		fmt.Fprintf(&body, "\n// %s\n", src.Path)
		for _, keyword := range []string{"type", "const", "var"} {
			for _, l := range lines[keyword] {
				body.WriteString(l + "\n")
			}
		}
	}
	if len(errs) > 0 {
		return "", nil, fmt.Errorf("%s", strings.Join(errs, "\n"))
	}
	for _, p := range order {
		if !aliased[p] {
			im.blank(p)
		}
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by grpc-service-mesh-gen. DO NOT EDIT.\n")
	out.WriteString("// Every generated identifier of the definitions tree, under one package.\n")
	fmt.Fprintf(&out, "\npackage %s\n\n", rootName)
	if len(im.local) > 0 {
		out.WriteString(im.block())
	}
	out.Write(body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return "", nil, fmt.Errorf("root package %s: formatting generated Go: %w", rootName, err)
	}
	return rootName + ".grpcmesh.go", src, nil
}

// goEnumAliases adds the enum type and each of its value constants.
func goEnumAliases(e *protogen.Enum, add func(keyword, name string)) {
	add("type", e.GoIdent.GoName)
	for _, v := range e.Values {
		add("const", v.GoIdent.GoName)
	}
}

// goMessageAliases adds each message type, then its nested enums and
// messages. Map entry messages have no generated type.
func goMessageAliases(msgs []*protogen.Message, add func(keyword, name string)) {
	for _, msg := range msgs {
		if msg.Desc.IsMapEntry() {
			continue
		}
		add("type", msg.GoIdent.GoName)
		for _, e := range msg.Enums {
			goEnumAliases(e, add)
		}
		goMessageAliases(msg.Messages, add)
	}
}
