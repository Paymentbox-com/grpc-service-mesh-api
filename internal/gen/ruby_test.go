func TestRubyFile_CrossDirectoryAndWellKnownRequires(t *testing.T) {
	_, src := render(t, map[string]string{
		"pbx/deployment.proto": pbxDeployment,
		"pbx/types/id.proto":   "syntax = \"proto3\";\npackage pbx.types;\nmessage Id {}\n",
		"pbx/lookup.proto": header + `package pbx;
import "pbx/types/id.proto";
import "google/protobuf/empty.proto";
service LookupService { rpc Find(google.protobuf.Empty) returns (pbx.types.Id); }
`,
	}, RubyFile)
	mustContain(t, src, "require \"grpc_service_mesh\"\nrequire \"google/protobuf/empty_pb\"\nrequire \"pbx/types/id_pb\"\n\nmodule Pbx\n")
	mustContain(t, src, "input: Google::Protobuf::Empty, output: Pbx::Types::Id, kind: :route")
}

func TestRubyFile_TopicOutputIsNotRequired(t *testing.T) {
	_, src := render(t, map[string]string{"pbx/deployment.proto": pbxDeployment, "pbx/api_key.proto": pbxService}, RubyFile)
	mustNotContain(t, src, "empty_pb")
	mustContain(t, src, "rpc :created, target: ApiKeyTargets::CREATED, input: Pbx::ApiKey, kind: :topic\n")
}

func TestRubyFile_MethodNamesSnakeCased(t *testing.T) {
	_, src := render(t, map[string]string{
		"pbx/deployment.proto": pbxDeployment,
		"pbx/api_key.proto": header + `package pbx;
message ApiKey {}
service ApiKeyService { rpc GetAPIKey(ApiKey) returns (ApiKey); }
`,
	}, RubyFile)
	mustContain(t, src, "    GET_API_KEY = ServiceMesh::Target.new(")
	mustContain(t, src, "rpc :get_api_key, target: ApiKeyTargets::GET_API_KEY,")
}

func TestRubyFile_ServiceNameKeptWhenOnlyTheSuffixRemains(t *testing.T) {
	_, src := render(t, map[string]string{
		"pbx/deployment.proto": pbxDeployment,
		"pbx/service.proto": header + `package pbx;
message Req {}
service Service { rpc Do(Req) returns (Req); }
`,
	}, RubyFile)
	mustContain(t, src, "  module ServiceTargets\n")
	mustContain(t, src, "  class Service < GrpcServiceMesh::RPCService\n")
	mustContain(t, src, "  class ServiceClient < GrpcServiceMesh::RPCClient\n")
}

func TestRubyFile_TwoServicesSeparatedByBlankLine(t *testing.T) {
	_, src := render(t, map[string]string{
		"pbx/deployment.proto": pbxDeployment,
		"pbx/api_key.proto":    pbxService,
		"pbx/ping.proto": header + `package pbx;
message Pong {}
service PingService { rpc Ping(Pong) returns (Pong); }
`,
	}, RubyFile)
	mustContain(t, src, "  class ApiKeyClient < GrpcServiceMesh::RPCClient\n    rpc :search, target: ApiKeyTargets::SEARCH, input: Pbx::ApiKey, output: Pbx::ApiKey, kind: :route\n    rpc :created, target: ApiKeyTargets::CREATED, input: Pbx::ApiKey, kind: :topic\n  end\n\n  module PingTargets\n")
}

func TestRubyServiceMaps_SecondTransportGetsSecondConstant(t *testing.T) {
	m := analyze(t, map[string]string{
		"pbx/deployment.proto":     pbxDeployment,
		"pbx/api_key.proto":        pbxService,
		"billing/deployment.proto": header + "package billing;\noption (mesh.transport) = \"http-json\";\n",
		"billing/invoice.proto": header + `package billing;
option ruby_package = "Money::Billing";
message Invoice {}
service InvoiceService { rpc Get(Invoice) returns (Invoice); }
`,
	})
	p, b, err := RubyServiceMaps(m)
	if err != nil {
		t.Fatal(err)
	}
	if p != "service_maps.rb" {
		t.Fatalf("path %q", p)
	}
	want := `# frozen_string_literal: true

# Generated by grpc-service-mesh-gen. DO NOT EDIT.
# One ServiceMap per transport, holding every Target served over it.

require "service_mesh"
require_relative "billing/billing_grpcmesh"
require_relative "pbx/pbx_grpcmesh"

module ServiceMaps
  HTTP_JSON = ServiceMesh::ServiceMap.new(targets: [
    Money::Billing::InvoiceTargets::GET
  ])

  NATS = ServiceMesh::ServiceMap.new(targets: [
    Pbx::ApiKeyTargets::SEARCH,
    Pbx::ApiKeyTargets::CREATED
  ])
end
`
	if string(b) != want {
		t.Fatalf("got:\n%s", b)
	}
}
