func TestRubyFile_CrossDirectoryAndWellKnownRequires(t *testing.T) {
	_, src := render(t, map[string]string{
		"shop/deployment.proto": shopDeployment,
		"shop/types/id.proto":   "syntax = \"proto3\";\npackage shop.types;\nmessage Id {}\n",
		"shop/lookup.proto": header + `package shop;
import "shop/types/id.proto";
import "google/protobuf/empty.proto";
service LookupService { rpc Find(google.protobuf.Empty) returns (shop.types.Id); }
`,
	}, RubyFile)
	mustContain(t, src, "require \"grpc_service_mesh\"\nrequire \"google/protobuf/empty_pb\"\nrequire \"shop/types/id_pb\"\n\nmodule Shop\n")
	mustContain(t, src, "input: Google::Protobuf::Empty, output: Shop::Types::Id, kind: :route")
}

func TestRubyFile_TopicOutputIsNotRequired(t *testing.T) {
	_, src := render(t, map[string]string{"shop/deployment.proto": shopDeployment, "shop/order.proto": shopService}, RubyFile)
	mustNotContain(t, src, "empty_pb")
	mustContain(t, src, "rpc :placed, target: OrderTargets::PLACED, input: Shop::Order, kind: :topic\n")
}

func TestRubyFile_MethodNamesSnakeCased(t *testing.T) {
	_, src := render(t, map[string]string{
		"shop/deployment.proto": shopDeployment,
		"shop/order.proto": header + `package shop;
message Order {}
service OrderService { rpc GetHTTPStatus(Order) returns (Order); }
`,
	}, RubyFile)
	mustContain(t, src, "    GET_HTTP_STATUS = ServiceMesh::Target.new(")
	mustContain(t, src, "rpc :get_http_status, target: OrderTargets::GET_HTTP_STATUS,")
}

func TestRubyFile_ServiceNameKeptWhenOnlyTheSuffixRemains(t *testing.T) {
	_, src := render(t, map[string]string{
		"shop/deployment.proto": shopDeployment,
		"shop/service.proto": header + `package shop;
message Req {}
service Service { rpc Do(Req) returns (Req); }
`,
	}, RubyFile)
	mustContain(t, src, "  module ServiceTargets\n")
	mustContain(t, src, "  class Service < GrpcServiceMesh::RPCService\n")
	mustContain(t, src, "  class ServiceClient < GrpcServiceMesh::RPCClient\n")
}

func TestRubyFile_TwoServicesSeparatedByBlankLine(t *testing.T) {
	_, src := render(t, map[string]string{
		"shop/deployment.proto": shopDeployment,
		"shop/order.proto":      shopService,
		"shop/ping.proto": header + `package shop;
message Pong {}
service PingService { rpc Ping(Pong) returns (Pong); }
`,
	}, RubyFile)
	mustContain(t, src, "  class OrderClient < GrpcServiceMesh::RPCClient\n    rpc :place, target: OrderTargets::PLACE, input: Shop::Order, output: Shop::Order, kind: :route\n    rpc :placed, target: OrderTargets::PLACED, input: Shop::Order, kind: :topic\n  end\n\n  module PingTargets\n")
}

func TestRubyServiceMaps_SecondTransportGetsSecondConstant(t *testing.T) {
	m := analyze(t, map[string]string{
		"shop/deployment.proto":    shopDeployment,
		"shop/order.proto":         shopService,
		"billing/deployment.proto": header + "package billing;\noption (mesh.transport) = \"http-json\";\n",
		"billing/invoice.proto": header + `package billing;
option ruby_package = "Money::Billing";
message Invoice {}
service InvoiceService { rpc Get(Invoice) returns (Invoice); }
`,
	})
	p, b, err := RubyServiceMaps(m)
	if err != nil {
		t.Fatal(err)
	}
	if p != "service_maps.rb" {
		t.Fatalf("path %q", p)
	}
	want := `# frozen_string_literal: true

# Generated by grpc-service-mesh-gen. DO NOT EDIT.
# One ServiceMap per transport, holding every Target served over it.

require "service_mesh"
require_relative "billing/billing_grpcmesh"
require_relative "shop/shop_grpcmesh"

module ServiceMaps
  HTTP_JSON = ServiceMesh::ServiceMap.new(targets: [
    Money::Billing::InvoiceTargets::GET
  ])

  NATS = ServiceMesh::ServiceMap.new(targets: [
    Shop::OrderTargets::PLACE,
    Shop::OrderTargets::PLACED
  ])
end
`
	if string(b) != want {
		t.Fatalf("got:\n%s", b)
	}
}
