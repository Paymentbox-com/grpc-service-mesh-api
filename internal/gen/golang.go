package gen

import (
	"bytes"
	"fmt"
	"go/format"
	"path"
	"sort"
	"strconv"
	"strings"
)

const (
	grpcmeshImport = "github.com/Paymentbox-com/grpc-service-mesh-go/grpcmesh"
	meshImport     = "github.com/Paymentbox-com/service-mesh-go/mesh"
)

// goImports assigns a local name to every imported package, numbering the
// name when it is taken.
type goImports struct {
	self  string            // import path of the package being written
	local map[string]string // import path -> local name
	name  map[string]string // import path -> package name
	taken map[string]bool
}

func newGoImports(self string, reserved ...string) *goImports {
	im := &goImports{self: self, local: map[string]string{}, name: map[string]string{}, taken: map[string]bool{}}
	for _, r := range reserved {
		im.taken[r] = true
	}
	return im
}

// use records an import and returns the identifier that refers to it.
func (im *goImports) use(importPath, name string) string {
	if local, ok := im.local[importPath]; ok {
		return local
	}
	local := name
	for i := 2; im.taken[local]; i++ {
		local = name + strconv.Itoa(i)
	}
	im.taken[local] = true
	im.local[importPath] = local
	im.name[importPath] = name
	return local
}

// blank records an import for its side effects alone, written as _ "path".
func (im *goImports) blank(importPath string) {
	if _, ok := im.local[importPath]; !ok {
		im.local[importPath] = "_"
	}
}

// block renders the import block, sorted by path. A package is aliased when
// its local name is not its package name.
func (im *goImports) block() string {
	paths := make([]string, 0, len(im.local))
	for p := range im.local {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	var b strings.Builder
	b.WriteString("import (\n")
	for _, p := range paths {
		b.WriteString("\t")
		if local := im.local[p]; local != im.name[p] {
			b.WriteString(local + " ")
		}
		b.WriteString(strconv.Quote(p) + "\n")
	}
	b.WriteString(")\n")
	return b.String()
}

// missingGoPackage is the error for a definitions file without go_package
// when Go is requested.
func missingGoPackage(file string) error {
	return fmt.Errorf("%s: go_package is not set; every definitions file sets go_package when Go is requested", file)
}

// goPackageOf returns the directory's go_package, checking that every file
// sets the same one.
func goPackageOf(d Directory) (string, error) {
	var value, first string
	for _, f := range d.Files {
		if f.GoPackage == "" {
			return "", missingGoPackage(f.Path)
		}
		if first == "" {
			value, first = f.GoPackage, f.Path
			continue
		}
		if f.GoPackage != value {
			return "", fmt.Errorf("%s: go_package differs: %q in %s, %q in %s", d.Path, value, first, f.GoPackage, f.Path)
		}
	}
	return value, nil
}

// goTypeRef returns the Go pointer type of a message from inside pkgPath.
func goTypeRef(im *goImports, m MessageRef) (string, error) {
	if m.GoPackage == "" {
		return "", fmt.Errorf("%s: go_package is not set; %s is referenced by a service", m.File, m.FullName)
	}
	p, name := splitGoPackage(m.GoPackage)
	if p == im.self {
		return "*" + goMessageName(m), nil
	}
	return "*" + im.use(p, name) + "." + goMessageName(m), nil
}

func goKind(k Kind) string {
	if k == Topic {
		return "mesh.KindTopic"
	}
	return "mesh.KindRoute"
}

// GoFile renders the directory's <dir>.grpcmesh.go.
func GoFile(d Directory) (string, []byte, error) {
	goPkg, err := goPackageOf(d)
	if err != nil {
		return "", nil, err
	}
	pkgPath, pkgName := splitGoPackage(goPkg)
	im := newGoImports(pkgPath, pkgName)
	var body bytes.Buffer
	hasMethod := false
	for _, s := range d.Services {
		if len(s.Methods) > 0 {
			hasMethod = true
		}
		if err := goService(&body, im, d, s); err != nil {
			return "", nil, err
		}
	}
	im.use(meshImport, "mesh")
	if hasMethod {
		im.use("context", "context")
		im.use(grpcmeshImport, "grpcmesh")
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by grpc-service-mesh-gen. DO NOT EDIT.\n")
	for _, f := range d.SourceFiles() {
		fmt.Fprintf(&out, "// source: %s\n", f)
	}
	fmt.Fprintf(&out, "\npackage %s\n\n", pkgName)
	out.WriteString(im.block())
	out.Write(body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return "", nil, fmt.Errorf("%s: formatting generated Go: %w", d.Path, err)
	}
	return path.Join(d.Path, path.Base(d.Path)+".grpcmesh.go"), src, nil
}

func goService(b *bytes.Buffer, im *goImports, d Directory, s Service) error {
	base := BaseName(s.Name)
	targets, client := base+"Targets", base+"Client"
	clientType := lowerFirst(client)
	type sig struct{ in, out string }
	sigs := make([]sig, len(s.Methods))
	for i, m := range s.Methods {
		in, err := goTypeRef(im, m.Input)
		if err != nil {
			return err
		}
		sigs[i].in = in
		if m.Kind == Route {
			out, err := goTypeRef(im, m.Output)
			if err != nil {
				return err
			}
			sigs[i].out = out
		}
	}
	segments := append(strings.Split(s.Package, "."), s.Name)

	fmt.Fprintf(b, "\n// %s holds one Target per rpc method of %s.\n", targets, s.Name)
	fmt.Fprintf(b, "var %s = struct {\n", targets)
	for _, m := range s.Methods {
		fmt.Fprintf(b, "\t%s mesh.Target\n", m.Name)
	}
	b.WriteString("}{\n")
	for _, m := range s.Methods {
		var segs []string
		for _, seg := range append(append([]string{}, segments...), m.Name) {
			segs = append(segs, strconv.Quote(seg))
		}
		fmt.Fprintf(b, "\t%s: mesh.Target{\n", m.Name)
		fmt.Fprintf(b, "\t\tSegments: []string{%s},\n", strings.Join(segs, ", "))
		fmt.Fprintf(b, "\t\tKind: %s,\n", goKind(m.Kind))
		b.WriteString("\t\tMetadata: map[string]string{\n")
		fmt.Fprintf(b, "\t\t\t\"deployment_group\": %s,\n", strconv.Quote(d.DeploymentGroup))
		fmt.Fprintf(b, "\t\t\t\"transport\": %s,\n", strconv.Quote(d.Transport))
		if m.ConsumerGroup != "" {
			fmt.Fprintf(b, "\t\t\t\"consumer_group\": %s,\n", strconv.Quote(m.ConsumerGroup))
		}
		b.WriteString("\t\t},\n\t},\n")
	}
	b.WriteString("}\n")

	fmt.Fprintf(b, "\n// %s is the RPCService for %s. A nil field is not\n// served.\n", s.Name, s.Name)
	fmt.Fprintf(b, "type %s struct {\n", s.Name)
	for i, m := range s.Methods {
		if m.Kind == Route {
			fmt.Fprintf(b, "\t%s func(context.Context, %s) (%s, error)\n", m.Name, sigs[i].in, sigs[i].out)
		} else {
			fmt.Fprintf(b, "\t%s func(context.Context, %s) error\n", m.Name, sigs[i].in)
		}
	}
	b.WriteString("}\n")

	b.WriteString("\n// Endpoints returns the Endpoints of the ROUTE methods that are set.\n")
	fmt.Fprintf(b, "func (s %s) Endpoints() []mesh.Endpoint {\n\tvar out []mesh.Endpoint\n", s.Name)
	for _, m := range s.Methods {
		if m.Kind == Route {
			fmt.Fprintf(b, "\tif s.%s != nil {\n\t\tout = append(out, grpcmesh.NewEndpoint(%s.%s, s.%s))\n\t}\n", m.Name, targets, m.Name, m.Name)
		}
	}
	b.WriteString("\treturn out\n}\n")

	b.WriteString("\n// Subscribers returns the Subscribers of the TOPIC methods that are set.\n")
	fmt.Fprintf(b, "func (s %s) Subscribers() []mesh.Subscriber {\n\tvar out []mesh.Subscriber\n", s.Name)
	for _, m := range s.Methods {
		if m.Kind == Topic {
			fmt.Fprintf(b, "\tif s.%s != nil {\n\t\tout = append(out, grpcmesh.NewSubscriber(%s.%s, s.%s))\n\t}\n", m.Name, targets, m.Name, m.Name)
		}
	}
	b.WriteString("\treturn out\n}\n")

	fmt.Fprintf(b, "\ntype %s struct{}\n", clientType)
	fmt.Fprintf(b, "\n// %s calls %s through grpcmesh.DefaultTransportRouter.\nvar %s %s\n", client, s.Name, client, clientType)
	for i, m := range s.Methods {
		if m.Kind == Route {
			fmt.Fprintf(b, "\n// %s calls the ROUTE method %s.\n", m.Name, m.Name)
			fmt.Fprintf(b, "func (%s) %s(ctx context.Context, req %s) (%s, error) {\n", clientType, m.Name, sigs[i].in, sigs[i].out)
			fmt.Fprintf(b, "\treturn grpcmesh.Call[%s, %s](ctx, %s.%s, req)\n}\n", sigs[i].in, sigs[i].out, targets, m.Name)
		} else {
			fmt.Fprintf(b, "\n// %s publishes to the TOPIC method %s.\n", m.Name, m.Name)
			fmt.Fprintf(b, "func (%s) %s(ctx context.Context, req %s) error {\n", clientType, m.Name, sigs[i].in)
			fmt.Fprintf(b, "\treturn grpcmesh.Publish(ctx, %s.%s, req)\n}\n", targets, m.Name)
		}
	}
	return nil
}

// GoServiceMaps renders servicemaps/servicemaps.go, one var per transport.
func GoServiceMaps(m *Model) (string, []byte, error) {
	im := newGoImports("", "servicemaps")
	im.use(meshImport, "mesh")
	var body bytes.Buffer
	for _, t := range m.Transports() {
		fmt.Fprintf(&body, "\n// %s holds every Target served over transport %s.\n", PascalCase(t), strconv.Quote(t))
		fmt.Fprintf(&body, "var %s = mesh.ServiceMap{Targets: []mesh.Target{\n", PascalCase(t))
		for _, d := range m.Directories {
			if d.Transport != t {
				continue
			}
			goPkg, err := goPackageOf(d)
			if err != nil {
				return "", nil, err
			}
			p, name := splitGoPackage(goPkg)
			local := im.use(p, name)
			for _, s := range d.Services {
				for _, mt := range s.Methods {
					fmt.Fprintf(&body, "\t%s.%sTargets.%s,\n", local, BaseName(s.Name), mt.Name)
				}
			}
		}
		body.WriteString("}}\n")
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by grpc-service-mesh-gen. DO NOT EDIT.\n\npackage servicemaps\n\n")
	out.WriteString(im.block())
	out.Write(body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return "", nil, fmt.Errorf("servicemaps: formatting generated Go: %w", err)
	}
	return "servicemaps/servicemaps.go", src, nil
}
